package envfile

import (
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"testing"
)

func write(t *testing.T, body string) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), "server.env")
	if err := os.WriteFile(p, []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
	return p
}

func TestParseLauncherDialect(t *testing.T) {
	p := write(t, "\ufeff# Generated by the launcher\n"+
		"CIX_API_KEY='abc123'\n"+
		"CIX_PORT='21847'\n"+
		"CIX_BOOTSTRAP_ADMIN_PASSWORD='it'\\''s a secret'\n"+
		"export CIX_BIND_ADDR=\"127.0.0.1\"\n"+
		"\n"+
		"  CIX_DATA_DIR = 'C:\\Users\\me\\.cix\\data'  \n"+
		"CIX_BARE=plain\n"+
		"not a pair\n"+
		"CIX_EMPTY=''\n")
	got, err := Parse(p)
	if err != nil {
		t.Fatal(err)
	}
	want := map[string]string{
		"CIX_API_KEY":                  "abc123",
		"CIX_PORT":                     "21847",
		"CIX_BOOTSTRAP_ADMIN_PASSWORD": "it's a secret",
		"CIX_BIND_ADDR":                "127.0.0.1",
		"CIX_DATA_DIR":                 `C:\Users\me\.cix\data`,
		"CIX_BARE":                     "plain",
		"CIX_EMPTY":                    "",
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("Parse = %#v\nwant   %#v", got, want)
	}
}

func TestLoadRealEnvironmentWins(t *testing.T) {
	t.Setenv("CIX_TEST_ENVFILE_SET", "from-env")
	t.Setenv("CIX_TEST_ENVFILE_EMPTY", "") // set-but-empty still counts as set
	os.Unsetenv("CIX_TEST_ENVFILE_NEW")
	t.Cleanup(func() { os.Unsetenv("CIX_TEST_ENVFILE_NEW") })

	p := write(t, "CIX_TEST_ENVFILE_SET='from-file'\n"+
		"CIX_TEST_ENVFILE_EMPTY='from-file'\n"+
		"CIX_TEST_ENVFILE_NEW='from-file'\n")
	set, err := Load(p)
	if err != nil {
		t.Fatal(err)
	}
	sort.Strings(set)
	if !reflect.DeepEqual(set, []string{"CIX_TEST_ENVFILE_NEW"}) {
		t.Fatalf("set = %v, want only the key that was unset", set)
	}
	if v := os.Getenv("CIX_TEST_ENVFILE_SET"); v != "from-env" {
		t.Errorf("real env was overridden: %q", v)
	}
	if v := os.Getenv("CIX_TEST_ENVFILE_EMPTY"); v != "" {
		t.Errorf("set-but-empty env was overridden: %q", v)
	}
	if v := os.Getenv("CIX_TEST_ENVFILE_NEW"); v != "from-file" {
		t.Errorf("missing key not filled from file: %q", v)
	}
}

