	dir := t.TempDir()
	key := bytes.Repeat([]byte{0xAB}, KeySize)
	t.Setenv("CIX_SECRET_KEY", hex.EncodeToString(key))
	t.Setenv("CIX_SECRET_KEYFILE", "")

	svc, err := Open(OpenOptions{DataDir: dir})
