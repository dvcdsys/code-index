func TestRoundTrip(t *testing.T) {
	dir := t.TempDir()
	t.Setenv("CIX_SECRET_KEY", "")
	t.Setenv("CIX_SECRET_KEYFILE", "")

	svc, err := Open(OpenOptions{DataDir: dir, AllowGenerate: true})
	if err != nil {
		t.Fatalf("Open: %v", err)
	}
	if !svc.Autogenerated() {
		t.Fatalf("expected autogenerated keyfile")
	}
	plain := []byte("ghp_super_secret_token_value")
	ct, err := svc.Encrypt(plain)
	if err != nil {
		t.Fatalf("Encrypt: %v", err)
	}
	if bytes.Contains(ct, plain) {
		t.Fatalf("ciphertext leaked plaintext bytes")
	}
	got, err := svc.Decrypt(ct)
	if err != nil {
		t.Fatalf("Decrypt: %v", err)
	}
	if !bytes.Equal(got, plain) {
		t.Fatalf("roundtrip mismatch: got %q want %q", got, plain)
	}
}

func TestPersistentKeyfile(t *testing.T) {
	dir := t.TempDir()
	t.Setenv("CIX_SECRET_KEY", "")
	t.Setenv("CIX_SECRET_KEYFILE", "")

	svc1, err := Open(OpenOptions{DataDir: dir, AllowGenerate: true})
	if err != nil {
		t.Fatalf("first Open: %v", err)
	}
	ct, err := svc1.Encrypt([]byte("hello"))
	if err != nil {
		t.Fatalf("Encrypt: %v", err)
	}

	// Second Open in the same dir must reuse the keyfile (NOT regenerate).
	svc2, err := Open(OpenOptions{DataDir: dir, AllowGenerate: true})
	if err != nil {
		t.Fatalf("second Open: %v", err)
	}
	if svc2.Autogenerated() {
		t.Fatalf("second Open should reuse the existing keyfile, not regenerate")
	}
	plain, err := svc2.Decrypt(ct)
	if err != nil {
		t.Fatalf("Decrypt with reused key: %v", err)
	}
	if string(plain) != "hello" {
		t.Fatalf("unexpected plaintext %q", plain)
	}
}

